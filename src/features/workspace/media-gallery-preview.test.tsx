import { fireEvent, render, screen, within } from "@testing-library/react";
import { describe, expect, it, vi } from "vitest";

import { MediaGalleryPreview } from "./media-gallery-preview";

describe("Media output gallery preview", () => {
  it("shows a mixed renderer-only gallery with truthful boundaries", () => {
    render(<MediaGalleryPreview />);

    const gallery = screen.getByRole("region", { name: "Media output gallery preview" });
    expect(within(gallery).getByRole("heading", { name: "Compare visual directions" })).toBeInTheDocument();
    expect(within(gallery).getByText("Preview only")).toBeInTheDocument();
    expect(within(gallery).getByText(/No generated bytes, provider result/i)).toBeInTheDocument();
    expect(within(gallery).getByRole("button", { name: "Inspect Command ring logo study" })).toBeInTheDocument();
    expect(within(gallery).getByRole("button", { name: "Inspect Omnia launch loop" })).toBeInTheDocument();
    expect(within(gallery).getByRole("button", { name: "Inspect Architecture narration" })).toBeInTheDocument();
  });

  it("filters media kinds and exposes the selected reference detail", () => {
    render(<MediaGalleryPreview />);

    const gallery = screen.getByRole("region", { name: "Media output gallery preview" });
    fireEvent.click(within(gallery).getByRole("button", { name: /^Video/i }));

    expect(within(gallery).getByRole("button", { name: "Inspect Omnia launch loop" })).toBeInTheDocument();
    expect(within(gallery).queryByRole("button", { name: "Inspect Command ring logo study" })).not.toBeInTheDocument();

    fireEvent.click(within(gallery).getByRole("button", { name: "Inspect Omnia launch loop" }));
    const detail = within(gallery).getByRole("complementary", { name: "Selected media output details" });
    expect(detail).toHaveTextContent("Cinematic motion");
    expect(detail).toHaveTextContent("16:9 · 8 s · 24 fps");
    expect(detail).toHaveTextContent(/no media bytes were loaded/i);
  });

  it("switches layouts and keeps history projections in the gallery", () => {
    render(
      <MediaGalleryPreview
        recentItems={[{
          id: "history-001",
          title: "User direction",
          kind: "image",
          subtitle: "Custom preset",
          detail: "4:5 · 1536 px · 1 variant",
          prompt: "A custom renderer-local direction",
          createdAt: "Queued in renderer preview",
          status: "queued",
        }]}
      />,
    );

    const gallery = screen.getByRole("region", { name: "Media output gallery preview" });
    fireEvent.click(within(gallery).getByRole("button", { name: "List view" }));
    expect(within(gallery).getByRole("button", { name: "List view" })).toHaveAttribute("aria-pressed", "true");
    fireEvent.click(within(gallery).getByRole("button", { name: "Inspect User direction" }));
    expect(within(gallery).getByRole("heading", { name: "User direction" })).toBeInTheDocument();

    fireEvent.click(within(gallery).getByRole("button", { name: /Use as next direction/i }));
    expect(within(gallery).getByRole("status")).toHaveTextContent(/no request was sent/i);
  });

  it("hands the selected reference to a draft callback without requiring generated media", () => {
    const onUseAsNextDirection = vi.fn();
    render(<MediaGalleryPreview onUseAsNextDirection={onUseAsNextDirection} />);

    const gallery = screen.getByRole("region", { name: "Media output gallery preview" });
    fireEvent.click(within(gallery).getByRole("button", { name: "Inspect Omnia launch loop" }));
    fireEvent.click(within(gallery).getByRole("button", { name: /Use as next direction/i }));

    expect(onUseAsNextDirection).toHaveBeenCalledWith(expect.objectContaining({
      id: "gallery-launch-loop",
      kind: "video",
      title: "Omnia launch loop",
    }));
    expect(within(gallery).getByRole("status")).toHaveTextContent(/no request was sent/i);
  });

  it("searches, refines by status, sorts, and clears gallery references locally", () => {
    render(<MediaGalleryPreview />);

    const gallery = screen.getByRole("region", { name: "Media output gallery preview" });
    const search = within(gallery).getByRole("searchbox", { name: "Search gallery references" });
    fireEvent.change(search, { target: { value: "architecture" } });

    expect(within(gallery).getByRole("button", { name: "Inspect Architecture narration" })).toBeInTheDocument();
    expect(within(gallery).queryByRole("button", { name: "Inspect Command ring logo study" })).not.toBeInTheDocument();
    expect(within(gallery).getByText("1 of 6 references shown")).toBeInTheDocument();

    fireEvent.change(within(gallery).getByRole("combobox", { name: "Gallery status filter" }), { target: { value: "attention" } });
    expect(within(gallery).getByText("Status: Needs endpoint")).toBeInTheDocument();

    fireEvent.click(within(gallery).getByRole("button", { name: "Clear gallery search" }));
    expect(within(gallery).getByRole("button", { name: "Inspect Architecture narration" })).toBeInTheDocument();
    expect(within(gallery).queryByRole("button", { name: "Inspect Omnia launch loop" })).not.toBeInTheDocument();

    fireEvent.click(within(gallery.querySelector(".media-gallery-preview__toolbar") as HTMLElement).getByRole("button", { name: "Clear" }));
    fireEvent.change(within(gallery).getByRole("combobox", { name: "Gallery sort" }), { target: { value: "title" } });
    const inspectButtons = within(gallery).getAllByRole("button", { name: /^Inspect / });
    expect(inspectButtons[0]).toHaveAccessibleName("Inspect Architecture narration");
    expect(within(gallery).getByText("6 of 6 references shown")).toBeInTheDocument();
  });

  it("creates, filters, renames, assigns, and removes session-only collections", () => {
    render(<MediaGalleryPreview />);

    const gallery = screen.getByRole("region", { name: "Media output gallery preview" });
    const collectionGroup = within(gallery).getByRole("region", { name: "Gallery collections" });
    fireEvent.change(within(collectionGroup).getByRole("textbox", { name: "New collection name" }), { target: { value: "Inbox" } });
    fireEvent.click(within(collectionGroup).getByRole("button", { name: "Create collection" }));

    expect(within(collectionGroup).getByRole("button", { name: /Inbox\s+0/ })).toHaveAttribute("aria-pressed", "true");
    fireEvent.click(within(collectionGroup).getByRole("button", { name: /All references/ }));
    fireEvent.click(within(gallery).getByRole("button", { name: "Select Command ring logo study for collection" }));
    fireEvent.click(within(collectionGroup).getByRole("button", { name: /Inbox\s+0/ }));
    fireEvent.click(within(collectionGroup).getByRole("button", { name: "Add to Inbox" }));
    fireEvent.click(within(collectionGroup).getByRole("button", { name: /Inbox\s+1/ }));

    expect(within(gallery).getByRole("button", { name: "Inspect Command ring logo study" })).toBeInTheDocument();
    expect(within(gallery).getByText("1 of 6 references shown")).toBeInTheDocument();

    fireEvent.click(within(collectionGroup).getByRole("button", { name: "Rename Inbox" }));
    fireEvent.change(within(collectionGroup).getByRole("textbox", { name: "Rename Inbox" }), { target: { value: "Pinned" } });
    fireEvent.click(within(collectionGroup).getByRole("button", { name: "Save Inbox" }));
    expect(within(collectionGroup).getByRole("button", { name: /Pinned\s+1/ })).toBeInTheDocument();

    fireEvent.click(within(collectionGroup).getByRole("button", { name: "Delete Pinned" }));
    expect(within(collectionGroup).queryByRole("button", { name: /Pinned/ })).not.toBeInTheDocument();
    expect(within(collectionGroup).getByText(/Deleted Pinned; references remain available as unsorted/)).toBeInTheDocument();
  });

  it("compares two references in a renderer-local direction workbench", () => {
    render(<MediaGalleryPreview />);

    const gallery = screen.getByRole("region", { name: "Media output gallery preview" });
    fireEvent.click(within(gallery).getByRole("button", { name: "Add Command ring logo study to comparison" }));
    fireEvent.click(within(gallery).getByRole("button", { name: "Add Omnia launch loop to comparison" }));
    fireEvent.click(within(gallery).getByRole("button", { name: "Compare 2/2" }));

    const compare = within(gallery).getByRole("region", { name: "Media reference comparison" });
    expect(within(compare).getByRole("heading", { name: "Compare references" })).toBeInTheDocument();
    expect(within(compare).getByText("Command ring logo study")).toBeInTheDocument();
    expect(within(compare).getByText("Omnia launch loop")).toBeInTheDocument();
    expect(within(compare).getAllByText("Different").length).toBeGreaterThan(0);
    expect(within(compare).getByText(/does not compare generated media bytes/i)).toBeInTheDocument();

    fireEvent.click(within(compare).getByRole("button", { name: "Remove Command ring logo study from comparison" }));
    expect(within(compare).getByText("Choose one more reference")).toBeInTheDocument();
  });
});
