import { describe, expect, it } from "vitest";

import {
  allowedMediaGenerationTransitions,
  buildMediaGenerationPreviewJob,
  canTransitionMediaGenerationJob,
  mediaGenerationActionAvailability,
  mediaGenerationStatusLabel,
  serializeMediaGenerationPreviewJob,
  transitionMediaGenerationPreviewJob,
  validateMediaGenerationDraft,
  type MediaGenerationDraft,
} from "./media-generation-orchestration";

const imageDraft: MediaGenerationDraft = {
  modality: "image",
  operation: "text-to-image",
  prompt: "A high-contrast developer workspace with a warm desk light",
  negativePrompt: "blurry, unreadable text",
  parameters: {
    aspectRatio: "16:9",
    width: 2048,
    height: 1152,
    variantCount: 2,
    seed: 42,
  },
};

describe("media generation orchestration preview contract", () => {
  it("validates request shape while keeping endpoint evidence as warnings", () => {
    const validation = validateMediaGenerationDraft(imageDraft);

    expect(validation.valid).toBe(true);
    expect(validation.errors).toEqual([]);
    expect(validation.warnings).toEqual(expect.arrayContaining([
      expect.stringContaining("Provider profile evidence"),
      expect.stringContaining("Capability snapshot evidence"),
    ]));
  });

  it("requires explicit authority for watermark cleanup", () => {
    const validation = validateMediaGenerationDraft({
      ...imageDraft,
      operation: "authorized-watermark-cleanup",
    });
    expect(validation.valid).toBe(false);
    expect(validation.errors).toEqual(expect.arrayContaining([
      expect.stringContaining("Watermark cleanup requires"),
    ]));

    const authorized = validateMediaGenerationDraft({
      ...imageDraft,
      operation: "authorized-watermark-cleanup",
      authority: { watermarkAuthorization: "explicit-permission" },
    });
    expect(authorized.valid).toBe(true);
  });

  it("mirrors the normative lifecycle without minting provider acceptance", () => {
    const job = buildMediaGenerationPreviewJob(imageDraft, {
      jobId: "preview:job-01",
      now: "2026-09-21T10:00:00.000Z",
    });
    expect(job.status).toBe("draft");
    expect(job.scope).toBe("renderer-session");
    expect(job.executionDisposition).toBe("preview-only");
    expect(job.providerAcceptance).toBe("not-sent");
    expect(job.providerJobHandle).toBeNull();
    expect(canTransitionMediaGenerationJob("draft", "validating")).toBe(true);
    expect(allowedMediaGenerationTransitions("draft")).toEqual(["validating", "cancelled"]);

    const validating = transitionMediaGenerationPreviewJob(job, "validating", { now: "2026-09-21T10:00:01.000Z" });
    expect(validating.ok).toBe(true);
    if (!validating.ok) return;
    expect(validating.job.status).toBe("validating");
    expect(validating.job.providerAcceptance).toBe("not-sent");

    const invalid = transitionMediaGenerationPreviewJob(validating.job, "completed");
    expect(invalid.ok).toBe(false);
    if (invalid.ok) return;
    expect(invalid.reason).toMatch(/cannot transition/);
  });

  it("blocks blind retry after an unknown external outcome", () => {
    const job = buildMediaGenerationPreviewJob(imageDraft);
    const unknown = transitionMediaGenerationPreviewJob(
      transitionMediaGenerationPreviewJob(job, "validating").job,
      "uploading",
    );
    expect(unknown.ok).toBe(true);
    if (!unknown.ok) return;
    const outcomeUnknown = transitionMediaGenerationPreviewJob(unknown.job, "outcome-unknown");
    expect(outcomeUnknown.ok).toBe(true);
    if (!outcomeUnknown.ok) return;

    const actions = mediaGenerationActionAvailability(outcomeUnknown.job);
    expect(actions.dispatch.available).toBe(false);
    expect(actions.retry.available).toBe(false);
    expect(actions.retry.reason).toMatch(/Blind retry is disabled/);
    expect(actions.reconcile.available).toBe(false);
  });

  it("serializes a copy-safe preview manifest with no generated bytes", () => {
    const job = buildMediaGenerationPreviewJob(imageDraft, { jobId: "preview:job-02" });
    const payload = serializeMediaGenerationPreviewJob(job);
    const parsed = JSON.parse(payload) as Record<string, unknown>;
    expect(parsed.schema).toBe("omnia.media-generation-orchestration.preview.v1");
    expect(parsed.scope).toBe("renderer-session");
    expect(parsed.providerCall).toBe("not-called-in-preview");
    expect(parsed.generatedBytes).toBe("not-generated-in-preview");
    expect(mediaGenerationStatusLabel("outcome-unknown")).toBe("Outcome unknown");
  });
});
