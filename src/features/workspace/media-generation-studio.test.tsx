import { fireEvent, render, screen, within } from "@testing-library/react";
import { describe, expect, it } from "vitest";

import { MediaGenerationStudio } from "./media-generation-studio";

describe("Media Generation Studio preview", () => {
  it("switches media modes and applies a preset without claiming provider dispatch", () => {
    render(<MediaGenerationStudio />);

    expect(screen.getByRole("heading", { name: "Media Generation Studio" })).toBeInTheDocument();
    expect(screen.getByRole("tab", { name: /Image Visual assets/i })).toHaveAttribute("aria-selected", "true");
    expect(screen.getByText(/does not upload files, call a provider, or write generated media/i)).toBeInTheDocument();

    fireEvent.click(screen.getByRole("tab", { name: /Video Motion studies/i }));
    expect(screen.getByRole("tab", { name: /Video Motion studies/i })).toHaveAttribute("aria-selected", "true");
    expect(screen.getByText(/Plan short clips with framing/i)).toBeInTheDocument();

    fireEvent.click(screen.getByRole("button", { name: /Cinematic motion/i }));
    expect(screen.getByRole("combobox", { name: "Media generation preset" })).toHaveValue("cinematic-motion");
    expect(screen.getByDisplayValue("slow push-in")).toBeInTheDocument();
  });

  it("queues a renderer-local request and previews it in history", () => {
    render(<MediaGenerationStudio />);

    fireEvent.change(screen.getByRole("textbox", { name: "Prompt" }), { target: { value: "A luminous command ring for a coder workspace" } });
    fireEvent.click(screen.getByRole("button", { name: /Queue generation preview/i }));

    expect(screen.getByRole("tab", { name: /Queue 3/i })).toHaveAttribute("aria-selected", "true");
    const queue = screen.getByRole("tabpanel", { name: /Queue 3/i });
    expect(within(queue).getByText("A luminous command ring for a coder workspace")).toBeInTheDocument();
    expect(within(queue).getByText(/no endpoint was called/i)).toBeInTheDocument();

    fireEvent.click(within(queue).getByRole("button", { name: /Preview A luminous command ring/i }));
    expect(screen.getByRole("tab", { name: /History 3/i })).toHaveAttribute("aria-selected", "true");
    expect(screen.getByRole("tabpanel", { name: /History 3/i })).toHaveTextContent("A luminous command ring for a coder workspace");
    expect(screen.getByRole("tabpanel", { name: /History 3/i })).toHaveTextContent(/Renderer result · just now/);
  });

  it("exports a portable request manifest while keeping generated bytes out of the payload", () => {
    render(<MediaGenerationStudio />);

    fireEvent.click(screen.getByRole("tab", { name: /History 2/i }));
    fireEvent.click(screen.getByRole("button", { name: "Preview export" }));
    const preview = screen.getByRole("region", { name: "Media generation export preview" });
    expect(within(preview).getByRole("code")).toHaveTextContent(/omnia\.media-generation\.preview\.v1/);
    expect(within(preview).getByRole("code")).toHaveTextContent(/outputBytes.*not-generated-in-preview/);

    fireEvent.change(within(preview).getByRole("combobox", { name: "Media generation export format" }), { target: { value: "markdown" } });
    expect(within(preview).getByRole("code")).toHaveTextContent(/# Omnia media generation preview/);
    expect(within(preview).getByText(/request metadata, not generated bytes or provider credentials/i)).toBeInTheDocument();
  });

  it("loads a gallery direction into the matching local draft without queueing it", () => {
    render(<MediaGenerationStudio />);

    fireEvent.click(screen.getByRole("tab", { name: /Gallery/i }));
    const gallery = screen.getByRole("region", { name: "Media output gallery preview" });
    fireEvent.click(within(gallery).getByRole("button", { name: "Inspect Omnia launch loop" }));
    fireEvent.click(within(gallery).getByRole("button", { name: /Use as next direction/i }));

    expect(screen.getByRole("tab", { name: /Create/i })).toHaveAttribute("aria-selected", "true");
    expect(screen.getByRole("tab", { name: /Video Motion studies/i })).toHaveAttribute("aria-selected", "true");
    expect(screen.getByRole("combobox", { name: "Media generation preset" })).toHaveValue("cinematic-motion");
    expect(screen.getByRole("textbox", { name: "Prompt" })).toHaveValue("A precise camera move through a dark developer workspace with warm desk light");
    expect(screen.getByRole("tab", { name: /Queue 2/i })).toBeInTheDocument();
    expect(screen.getByText(/no generation request was sent/i)).toBeInTheDocument();
  });

  it("keeps a mode-aware composition board visible without generating media bytes", () => {
    render(<MediaGenerationStudio />);

    const imagePreview = screen.getByRole("region", { name: "Image composition preview" });
    expect(within(imagePreview).getByText("Composition board")).toBeInTheDocument();
    expect(within(imagePreview).getByText("Preview only")).toBeInTheDocument();
    expect(within(imagePreview).getByRole("checkbox", { name: "Show composition guides" })).not.toBeChecked();

    fireEvent.click(within(imagePreview).getByRole("checkbox", { name: "Show composition guides" }));
    expect(within(imagePreview).getByRole("checkbox", { name: "Show composition guides" })).toBeChecked();

    fireEvent.click(screen.getByRole("tab", { name: /Audio Voice & sound/i }));
    const audioPreview = screen.getByRole("region", { name: "Audio composition preview" });
    expect(within(audioPreview).getByText("Sound bed rehearsal")).toBeInTheDocument();
    expect(within(audioPreview).getByText(/neutral narrator/)).toBeInTheDocument();
    expect(within(audioPreview).getByText(/no generated media bytes/i)).toBeInTheDocument();
  });

  it("shows a truthful lifecycle and recovery rail for the renderer draft", () => {
    render(<MediaGenerationStudio />);

    const rail = screen.getByRole("region", { name: "Media orchestration preview" });
    expect(within(rail).getByText("Job lifecycle and recovery")).toBeInTheDocument();
    expect(within(rail).getByText("No dispatch")).toBeInTheDocument();
    expect(within(rail).getByText("Not observed")).toBeInTheDocument();
    expect(within(rail).getByText("Not sent")).toBeInTheDocument();
    expect(within(rail).getByText(/Native acceptance, idempotency, polling/i)).toBeInTheDocument();

    fireEvent.click(within(rail).getByText("Recovery and authority boundaries"));
    expect(within(rail).getByText(/Provider dispatch is native-owned/i)).toBeInTheDocument();
    expect(within(rail).getByText(/Retry is available only after a known failure/i)).toBeInTheDocument();

    fireEvent.change(screen.getByRole("textbox", { name: "Prompt" }), { target: { value: "" } });
    expect(within(rail).getByText("Needs input")).toBeInTheDocument();
  });

  it("builds and carries a renderer-local video storyboard through queue and export", () => {
    render(<MediaGenerationStudio />);

    fireEvent.click(screen.getByRole("tab", { name: /Video Motion studies/i }));
    fireEvent.click(screen.getByRole("button", { name: "Storyboard sequence" }));
    const storyboard = screen.getByRole("region", { name: "Video storyboard preview" });
    expect(within(storyboard).getByText("3 shots · 8 s")).toBeInTheDocument();

    fireEvent.change(within(storyboard).getByRole("combobox", { name: "Shot 1 duration" }), { target: { value: "5" } });
    expect(within(storyboard).getByText("3 shots · 10 s")).toBeInTheDocument();
    fireEvent.click(within(storyboard).getByRole("button", { name: "Move shot 2 up" }));
    expect(within(storyboard).getByRole("textbox", { name: "Shot 1 title" })).toHaveValue("Reveal the detail");

    fireEvent.click(screen.getByRole("button", { name: /Queue generation preview/i }));
    const queue = screen.getByRole("tabpanel", { name: /Queue 3/i });
    expect(within(queue).getByText(/Storyboard · 3 shots/)).toBeInTheDocument();
    expect(within(queue).getByText(/10 s/)).toBeInTheDocument();
    fireEvent.click(within(queue).getByRole("button", { name: /Preview .*developer workspace/i }));

    fireEvent.click(screen.getByRole("button", { name: "Preview export" }));
    const exportPreview = screen.getByRole("region", { name: "Media generation export preview" });
    expect(within(exportPreview).getByRole("code")).toHaveTextContent(/storyboard/);
    expect(within(exportPreview).getByRole("code")).toHaveTextContent(/Reveal the detail/);
    expect(within(exportPreview).getByRole("code")).toHaveTextContent(/not-called-in-preview/);
  });

  it("keeps media tabs linked to their panels and supports roving keyboard navigation", () => {
    render(<MediaGenerationStudio />);

    const modeTablist = screen.getByRole("tablist", { name: "Media generation modes" });
    const imageTab = within(modeTablist).getByRole("tab", { name: /Image Visual assets/i });
    const videoTab = within(modeTablist).getByRole("tab", { name: /Video Motion studies/i });
    expect(imageTab).toHaveAttribute("aria-controls", "media-studio-panel-create");
    expect(imageTab).toHaveAttribute("tabindex", "0");
    expect(videoTab).toHaveAttribute("tabindex", "-1");

    imageTab.focus();
    fireEvent.keyDown(imageTab, { key: "ArrowRight" });
    expect(videoTab).toHaveFocus();
    expect(videoTab).toHaveAttribute("aria-selected", "true");

    const studioTablist = screen.getByRole("tablist", { name: "Media studio views" });
    const createTab = within(studioTablist).getByRole("tab", { name: "Create" });
    const createPanel = screen.getByRole("tabpanel", { name: /Create/i });
    expect(createTab).toHaveAttribute("aria-controls", createPanel.id);
    expect(createPanel).toHaveAttribute("aria-labelledby", createTab.id);

    fireEvent.keyDown(createTab, { key: "End" });
    const historyTab = within(studioTablist).getByRole("tab", { name: /History 2/i });
    expect(historyTab).toHaveFocus();
    expect(historyTab).toHaveAttribute("aria-selected", "true");
  });

  it("rehearses pause, retry, cancel, and re-queue lifecycle actions locally", () => {
    render(<MediaGenerationStudio />);

    fireEvent.click(screen.getByRole("tab", { name: /Queue 2/i }));
    const queuePanel = screen.getByRole("tabpanel", { name: /Queue 2/i });
    const launchLoopCard = screen.getByText("Omnia launch loop").closest("article");
    const narrationCard = screen.getByText("Architecture narration").closest("article");
    expect(launchLoopCard).not.toBeNull();
    expect(narrationCard).not.toBeNull();

    fireEvent.click(within(launchLoopCard!).getByRole("button", { name: "Pause Omnia launch loop" }));
    expect(within(launchLoopCard!).getByText("Paused preview")).toBeInTheDocument();
    fireEvent.click(within(launchLoopCard!).getByRole("button", { name: "Resume Omnia launch loop" }));
    expect(within(launchLoopCard!).getByText("Queued preview")).toBeInTheDocument();

    fireEvent.click(within(narrationCard!).getByRole("button", { name: "Retry Architecture narration" }));
    expect(within(narrationCard!).getByText("Queued preview")).toBeInTheDocument();

    fireEvent.click(within(launchLoopCard!).getByRole("button", { name: "Cancel Omnia launch loop" }));
    expect(screen.getByRole("tab", { name: /Queue 1/i })).toHaveAttribute("aria-selected", "true");
    expect(screen.getByRole("tab", { name: /History 3/i })).toBeInTheDocument();

    fireEvent.click(screen.getByRole("tab", { name: /History 3/i }));
    const historyCard = screen.getByRole("button", { name: "Queue Omnia launch loop again" }).closest("article");
    expect(historyCard).not.toBeNull();
    expect(within(historyCard!).getByText("Cancelled preview")).toBeInTheDocument();
    fireEvent.click(within(historyCard!).getByRole("button", { name: "Queue Omnia launch loop again" }));
    expect(screen.getByRole("tab", { name: /Queue 2/i })).toHaveAttribute("aria-selected", "true");
    expect(screen.getByText(/Re-queued Omnia launch loop in the renderer preview/i)).toBeInTheDocument();
    expect(within(queuePanel).queryByText("Omnia launch loop")).not.toBeInTheDocument();
  });
});
