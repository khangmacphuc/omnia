#!/usr/bin/env node

/* Generate the small, renderer-safe catalog consumed by Omnia's capability
 * registry. The full inventory remains in artifacts/upstream-ui when an audit
 * checkout is present. Release checkouts also carry a compact metadata
 * snapshot so CI can reproduce the catalog without vendoring raw profiles,
 * per-file hashes or sensitive data. */
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "../..");
const inputPath = path.join(root, "artifacts", "upstream-ui", "upstream-inventory-current.json");
const snapshotPath = path.join(root, "src", "domain", "upstream-capability-catalog.snapshot.json");
const outputPath = path.join(root, "src", "domain", "upstream-capability-catalog.ts");
const checkOnly = process.argv.includes("--check");
const selectedInputPath = fs.existsSync(inputPath) ? inputPath : snapshotPath;
if (!fs.existsSync(selectedInputPath)) {
  throw new Error(`Upstream inventory is missing. Expected ${inputPath} or ${snapshotPath}.`);
}
const input = JSON.parse(fs.readFileSync(selectedInputPath, "utf8"));

const modules = input.modules.map((item) => ({
  id: item.id,
  category: item.category,
  name: item.name,
  root: item.root,
  classification: item.sourceClassification,
  integrationMode: item.integration.mode,
  integrationReason: item.integration.reason,
  totalFiles: item.facts.totalFiles,
  sourceFiles: item.facts.sourceFiles,
  totalBytes: item.facts.totalBytes,
  sensitiveFileCount: item.facts.sensitiveFileCount,
  licenseSignal: item.facts.licenseSignal,
  gitHead: item.gitHead,
  manifests: item.manifests.slice(0, 16),
  entryCandidates: item.entryCandidates.slice(0, 16),
}));

const generated = `/**
 * Renderer-safe projection of the upstream extraction inventory.
 *
 * The complete file/hash evidence lives in
 * \`artifacts/upstream-ui/upstream-inventory-current.json\`. This catalog only
 * carries bounded metadata needed to route a capability to an adapter. It
 * never exposes credentials, browser profile state, raw file contents or
 * arbitrary executable paths to model-authored tool calls.
 *
 * Generated by scripts/upstream-preview/generate-upstream-capability-catalog.cjs.
 */

export const UPSTREAM_CAPABILITY_CATALOG_SCHEMA_VERSION = 1 as const;

export type UpstreamIntegrationMode =
  | "adapter-first"
  | "evidence-only"
  | "isolated-runtime"
  | "native-adapter"
  | "network-adapter"
  | "process-adapter"
  | "review"
  | "workflow-adapter";

export type UpstreamSourceClassification =
  | "bundle-or-native-artifact"
  | "empty-or-unreadable"
  | "reconstructed-or-test-artifact"
  | "runtime-state-or-profile"
  | "source-or-extracted-code"
  | "upstream-source-or-buildable-tree";

export interface UpstreamCapabilityDescriptor {
  readonly id: string;
  readonly category: string;
  readonly name: string;
  readonly root: string;
  readonly classification: UpstreamSourceClassification;
  readonly integrationMode: UpstreamIntegrationMode;
  readonly integrationReason: string;
  readonly totalFiles: number;
  readonly sourceFiles: number;
  readonly totalBytes: number;
  readonly sensitiveFileCount: number;
  readonly licenseSignal: boolean;
  readonly gitHead: string | null;
  readonly manifests: readonly string[];
  readonly entryCandidates: readonly string[];
}

const CATALOG: readonly UpstreamCapabilityDescriptor[] = Object.freeze(${JSON.stringify(modules, null, 2)}.map((item) => Object.freeze({
  ...item,
  manifests: Object.freeze(item.manifests),
  entryCandidates: Object.freeze(item.entryCandidates),
}) as unknown as UpstreamCapabilityDescriptor));

function assertId(id: string): string {
  const normalized = id.trim();
  if (!normalized || normalized.includes("\\\\") || normalized.includes("..")) {
    throw new Error("Invalid upstream capability id.");
  }
  return normalized;
}

export function listUpstreamCapabilities(): readonly UpstreamCapabilityDescriptor[] {
  return CATALOG;
}

export function findUpstreamCapability(id: string): UpstreamCapabilityDescriptor | undefined {
  const normalized = assertId(id);
  return CATALOG.find((item) => item.id === normalized);
}

export function requireUpstreamCapability(id: string): UpstreamCapabilityDescriptor {
  const item = findUpstreamCapability(id);
  if (!item) throw new Error(\`Unknown upstream capability: \${id}\`);
  return item;
}

export function listUpstreamCapabilitiesByCategory(category: string): readonly UpstreamCapabilityDescriptor[] {
  const normalized = category.trim().toLowerCase();
  if (!normalized) return Object.freeze([]);
  return CATALOG.filter((item) => item.category === normalized);
}

export function listRunnableUpstreamCapabilities(): readonly UpstreamCapabilityDescriptor[] {
  return CATALOG.filter((item) =>
    item.sensitiveFileCount === 0 &&
    (item.integrationMode === "adapter-first" ||
      item.integrationMode === "process-adapter" ||
      item.integrationMode === "isolated-runtime" ||
      item.integrationMode === "native-adapter" ||
      item.integrationMode === "network-adapter" ||
      item.integrationMode === "workflow-adapter"),
  );
}

export function createUpstreamAdapterPlan(id: string): {
  readonly capabilityId: string;
  readonly mode: UpstreamIntegrationMode;
  readonly root: string;
  readonly entryCandidates: readonly string[];
  readonly requiresHumanReview: boolean;
  readonly evidenceOnly: boolean;
} {
  const item = requireUpstreamCapability(id);
  return Object.freeze({
    capabilityId: item.id,
    mode: item.integrationMode,
    root: item.root,
    entryCandidates: item.entryCandidates,
    requiresHumanReview: item.integrationMode === "evidence-only" || item.integrationMode === "review" || item.licenseSignal === false,
    evidenceOnly: item.integrationMode === "evidence-only",
  });
}

export function upstreamCapabilitySummary(): {
  readonly total: number;
  readonly categories: number;
  readonly sourceFiles: number;
  readonly totalFiles: number;
  readonly totalBytes: number;
  readonly evidenceOnly: number;
  readonly runnable: number;
} {
  const categories = new Set(CATALOG.map((item) => item.category));
  return Object.freeze({
    total: CATALOG.length,
    categories: categories.size,
    sourceFiles: CATALOG.reduce((sum, item) => sum + item.sourceFiles, 0),
    totalFiles: CATALOG.reduce((sum, item) => sum + item.totalFiles, 0),
    totalBytes: CATALOG.reduce((sum, item) => sum + item.totalBytes, 0),
    evidenceOnly: CATALOG.filter((item) => item.integrationMode === "evidence-only").length,
    runnable: listRunnableUpstreamCapabilities().length,
  });
}
`;

if (checkOnly) {
  const current = fs.readFileSync(outputPath, "utf8");
  // Windows checkouts may normalize the tracked TypeScript file to CRLF while
  // the generator emits LF. Compare logical content so the gate is portable
  // across Windows and Linux runners.
  if (current.replaceAll("\r\n", "\n") !== generated.replaceAll("\r\n", "\n")) {
    console.error("Upstream capability catalog is stale. Run npm run inventory:catalog.");
    process.exitCode = 1;
  } else {
    console.log(JSON.stringify({ output: path.relative(root, outputPath).replaceAll(path.sep, "/"), modules: modules.length, checked: true }));
  }
} else {
  fs.writeFileSync(outputPath, generated);
  console.log(JSON.stringify({ output: path.relative(root, outputPath).replaceAll(path.sep, "/"), modules: modules.length }));
}

